// ω99-98 — the pet sprite: the root element the tests (and pet.css) key on,
// plus the default skin's figure. Import note: ./skins/index.js
// imports DefaultPetSkin + sheetSkin from here, while this file imports ONLY
// TYPES back (erased at runtime) — a single directed edge, never a cycle.
// Registry lookup therefore lives with the state core (pet/PetApp.tsx via
// signals' usePetSkinSignal, the registry's only consumer), which keeps
// this component pure display.
// ω99-108 — the figure swapped from div+CSS (circle body + two eyes) to the
// project logo slime PNG. ω99-111 — the figure swapped again from a single
// <img> to a 2-frame sheet background-div: steps(1) blink needs
// background-position, which an img cannot animate without swapping src
// (a flash per blink). The sheet's left frame is eyes-open, right frame
// eyes-closed; pet.css's pet-blink flips between them. The sheets are
// generated by scripts/make-logo-sprite.py → public/pet/skin-<id>.png.
import type { PointerEvent as ReactPointerEvent } from "react";
import type { ReactElement } from "react";
import type { PetSkin, PetSkinProps } from "./skins/index.js";
import type { PetDisplayState } from "./pet-state.js";

/** ω99-111 — the sheet skin factory: one 2-frame sprite sheet = one skin.
 *  The div carries ONLY the backgroundImage; every geometric (96px wide,
 *  pinned aspect-ratio, bottom-anchored) and motion property lives in
 *  pet.css keyed off the class, so all skins share one DOM contract and
 *  switching skins swaps nothing but the url. */
export function sheetSkin(sheetUrl: string): (props: PetSkinProps) => ReactElement {
  return function SheetPetSkin(_props: PetSkinProps) {
    return (
      <div className="pet-figure">
        <div className="pet-sprite-img" style={{ backgroundImage: `url(${sheetUrl})` }} />
      </div>
    );
  };
}

/** The default skin's figure — state-agnostic markup; the seven-state motion
 *  keys off the ancestor [data-pet-state] in pet.css, so the figure never
 *  branches on state in JS — it just lands CSS that does. Kept as its own
 *  export (not an inline registry entry) because tests and skins/index.ts
 *  import it directly — the ω99-98 import contract, unchanged. */
export const DefaultPetSkin = sheetSkin("/pet/skin-default.png");

export interface PetSpriteProps {
  /** What the pet shows — the machine's display, or "drag" while grabbed. */
  display: PetDisplayState;
  /** The registry id of the skin ACTUALLY rendered — stamped on data-skin
   *  (id resolution lives in signals' usePetSkinSignal + PetApp, so
   *  data-skin never names a skin that is not the one on screen). */
  skinId?: string;
  /** The figure renderer; defaults to the built-in DefaultPetSkin. */
  figure?: PetSkin["component"];
  /** Power-saving pin: true stamps data-paused (pet.css freezes animation). */
  paused?: boolean;
  /** ω99-278: #4 — 戳一戳纪元：++ 即重挂 Q 弹层（重启动画——motionEpoch 同
   *  技法但只重挂这一层，不重挂整个 PetSprite）。ω99-282: #3 — 只当重挂
   *  key：任何值都不再推断 data-poked（278 的 >0 推断退役）。 */
  pokeEpoch?: number;
  /** ω99-282（续，标记 #3 见上）— data-poked 瞬时门：仅戳后
   *  POKE_SQUASH_MS(600ms) 窗内为 true（interaction.ts 的 pokeFlash）；窗外任何
   *  重挂（wake nudge/StrictMode/epoch++）都挂不上——pet-squash 单次无
   *  fill，窗外撤属性零视觉差。 */
  poked?: boolean;
  /** pointerdown on the sprite — the window-drag seam (wired in pet/interaction.ts). */
  onPointerDown?: (event: ReactPointerEvent<HTMLDivElement>) => void;
}

/** The sprite shell: root contract attributes + the skin's figure. Pure
 *  display — no machine, no listeners beyond the passed handler; drag and
 *  paused bookkeeping live in pet/PetApp.tsx + pet/interaction.ts, the machine
 *  in pet-state.ts. */
export function PetSprite({
  display,
  skinId = "default",
  figure: Figure = DefaultPetSkin,
  paused = false,
  pokeEpoch,
  poked,
  onPointerDown,
}: PetSpriteProps) {
  return (
    <div
      className="pet-root"
      data-pet-root=""
      data-skin={skinId}
      data-pet-state={display}
      data-paused={paused ? "" : undefined}
      title="wudao pet"
      onPointerDown={onPointerDown}
    >
      {/* ω99-278（续，标记 #4 见上）— Q 弹层：包 figure 的可重挂内层
          （key=pokeEpoch，重挂即 pet-squash 重启）。垫在 .pet-root 内、
          figure 外：外层 transform 会给 fixed 后代造 containing block
          （破坏 .pet-root 定位），内层无此险；既有选择器全是后代形
          （[data-pet-state] .pet-sprite-img / .pet-figure），垫层零演进。 */}
      {/* ω99-282（续，标记 #3 见上）— data-poked 改瞬时门（poked prop）：
          pokeEpoch 只当 key，不再推断——窗外重挂不重放 squash。 */}
      <div
        className="pet-poke-layer"
        key={pokeEpoch ?? 0}
        data-poked={poked ? "" : undefined}
      >
        <Figure display={display} />
      </div>
    </div>
  );
}
